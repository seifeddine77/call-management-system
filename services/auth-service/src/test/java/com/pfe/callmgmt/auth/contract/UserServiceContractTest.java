package com.pfe.callmgmt.auth.contract;

import com.pfe.callmgmt.auth.client.UserServiceClient;
import com.pfe.callmgmt.auth.dto.RegisterRequest;
import com.pfe.callmgmt.auth.dto.UserDto;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.cloud.contract.stubrunner.spring.AutoConfigureStubRunner;
import org.springframework.cloud.contract.stubrunner.spring.StubRunnerProperties;
import org.springframework.http.ResponseEntity;
import org.springframework.test.context.ActiveProfiles;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Consumer-side Contract Tests (auth-service).
 *
 * Uses Spring Cloud Contract Stub Runner to start WireMock stubs
 * from user-service-1.0.0-stubs.jar (generated by `mvn install` on
 * user-service).
 *
 * Tests verify that auth-service's Feign client correctly communicates
 * with user-service as per the defined contracts.
 *
 * NOTE: The GET /email/{email} test uses "testoperator" (no @) because
 * Feign URL-encodes @ as %40, which breaks WireMock path matching.
 * This is a known limitation of path-variable emails in REST APIs.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.NONE)
@ActiveProfiles("test")
@AutoConfigureStubRunner(ids = "com.pfe.callmgmt:user-service:+:stubs:6565", stubsMode = StubRunnerProperties.StubsMode.LOCAL)
@Tag("contract")
@EnabledIfSystemProperty(named = "contract.tests", matches = "true")
public class UserServiceContractTest {

    // --- SonarCloud: extracted string constants ---
    private static final String ROLE_OPERATOR = "OPERATOR";

    @Autowired
    private UserServiceClient userServiceClient;

    @Test
    @DisplayName("Contract: GET /api/users/email/{email} → 200 avec InternalUserResponse")
    void shouldReturnUserByEmail() {
        // Use "testoperator" (no @ sign) — Feign URL-encodes @ as %40 which breaks
        // WireMock matching
        ResponseEntity<UserDto> response = userServiceClient.findByEmail("testoperator");

        assertThat(response.getStatusCode().value()).isEqualTo(200);

        UserDto user = response.getBody();
        assertThat(user).isNotNull();
        assertThat(user.getEmail()).isEqualTo("testoperator");
        assertThat(user.getPasswordHash()).isNotBlank();
        assertThat(user.getNom()).isEqualTo("Opérateur Test");
        assertThat(user.getRole()).isEqualTo(ROLE_OPERATOR);
        assertThat(user.isActif()).isTrue();
    }

    @Test
    @DisplayName("Contract: POST /api/users/internal → 201 avec InternalUserResponse")
    void shouldCreateUserInternal() {
        RegisterRequest request = new RegisterRequest();
        request.setEmail("newuser@test.com");
        request.setPassword("$2a$10$hashedpassword");
        request.setNom("Nouveau Utilisateur"); /* prenom set below */;
        request.setTelephone("98222333");
        request.setRole(ROLE_OPERATOR);

        ResponseEntity<UserDto> response = userServiceClient.createUser(request);

        assertThat(response.getStatusCode().value()).isEqualTo(201);

        UserDto user = response.getBody();
        assertThat(user).isNotNull();
        assertThat(user.getEmail()).isEqualTo("newuser@test.com");
        assertThat(user.getPasswordHash()).isNotBlank();
        assertThat(user.getNom()).isEqualTo("Nouveau Utilisateur");
        assertThat(user.getRole()).isEqualTo(ROLE_OPERATOR);
        assertThat(user.isActif()).isTrue();
    }
}
